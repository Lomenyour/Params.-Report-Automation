import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path


def analyze_vna_distribution(data):
    """
    Анализ распределения значений ВНА.

    Первый столбец таблицы  - дата/время.
    Второй столбец          - значение ВНА.

    Значения ВНА разбиваются на фиксированные интервалы:
    0-1, 1-2, 2-3, ..., 99-100.

    Возвращает:
    1. Таблицу распределения.
    2. Интервал, содержащий максимальное количество измерений.
    """

    # Названия столбцов
    date_col = data.columns[0]
    vna_col = data.columns[1]

    # Копируем необходимые данные
    df = data[[date_col, vna_col]].copy()

    # ---------------------------------------------------------
    # Преобразование ВНА в числовой формат
    # ---------------------------------------------------------

    # Поддержка как точки, так и запятой
    df[vna_col] = (
        df[vna_col]
        .astype(str)
        .str.replace(",", ".", regex=False)
    )

    df[vna_col] = pd.to_numeric(
        df[vna_col],
        errors="coerce"
    )

    # Удаляем строки без корректного значения ВНА
    df = df.dropna(subset=[vna_col])

    # Оставляем только физически допустимый диапазон
    df = df[
        (df[vna_col] >= 0) &
        (df[vna_col] <= 100)
    ]

    if df.empty:
        raise ValueError(
            "В таблице отсутствуют корректные значения ВНА."
        )

    # ---------------------------------------------------------
    # Создание интервалов
    # ---------------------------------------------------------

    # Границы:
    # 0, 1, 2, ..., 100
    bins = np.arange(0, 101, 1)

    # Считаем количество значений в каждом интервале
    counts, edges = np.histogram(
        df[vna_col],
        bins=bins
    )

    # ---------------------------------------------------------
    # Создаем таблицу распределения
    # ---------------------------------------------------------

    distribution = pd.DataFrame({
        "ВНА от": edges[:-1],
        "ВНА до": edges[1:],
        "Количество": counts
    })

    # Добавляем название диапазона
    distribution["Интервал ВНА"] = (
        distribution["ВНА от"].astype(int).astype(str)
        + "-"
        + distribution["ВНА до"].astype(int).astype(str)
    )

    # Доля времени/измерений
    distribution["Доля, %"] = (
        distribution["Количество"]
        / distribution["Количество"].sum()
        * 100
    )

    # ---------------------------------------------------------
    # Поиск наиболее частого диапазона
    # ---------------------------------------------------------

    max_index = distribution["Количество"].idxmax()

    best_interval = distribution.loc[max_index]

    return df, distribution, best_interval


